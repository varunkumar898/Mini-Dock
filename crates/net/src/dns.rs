//! DNS configuration generator for `alphen-box` containers.

use alphen_common::{AlphenError, Result};
use std::fs;
use std::path::Path;

/// Default public DNS fallback servers when host has no readable DNS.
pub const DEFAULT_DNS_SERVERS: &[&str] = &["8.8.8.8", "1.1.1.1"];

/// Generates and writes `/etc/resolv.conf` into the container's root filesystem.
pub fn write_resolv_conf(target_rootfs: &Path, dns_overrides: &[String]) -> Result<()> {
    let etc_dir = target_rootfs.join("etc");
    if !etc_dir.exists() {
        fs::create_dir_all(&etc_dir).map_err(|e| {
            AlphenError::Runtime(format!(
                "Failed to create /etc in rootfs {}: {e}",
                target_rootfs.display()
            ))
        })?;
    }

    let mut servers: Vec<String> = Vec::new();

    if !dns_overrides.is_empty() {
        for s in dns_overrides {
            servers.push(s.clone());
        }
    } else {
        // Attempt to read host's /etc/resolv.conf
        let host_resolv = Path::new("/etc/resolv.conf");
        if host_resolv.exists() {
            if let Ok(content) = fs::read_to_string(host_resolv) {
                for line in content.lines() {
                    let trimmed = line.trim();
                    if trimmed.starts_with("nameserver") {
                        if let Some((_, ns)) = trimmed.split_once(char::is_whitespace) {
                            let ns = ns.trim();
                            // Skip local loopback systemd-resolved stubs (127.0.0.53 / 127.0.0.1)
                            // because loopback inside container won't reach host systemd-resolved
                            if !ns.starts_with("127.") && !ns.is_empty() {
                                servers.push(ns.to_string());
                            }
                        }
                    }
                }
            }
        }

        // If no external servers discovered, use robust fallback
        if servers.is_empty() {
            for fallback in DEFAULT_DNS_SERVERS {
                servers.push((*fallback).to_string());
            }
        }
    }

    let mut resolv_content = String::from("# Generated by alphen-box\n");
    for ns in &servers {
        resolv_content.push_str(&format!("nameserver {ns}\n"));
    }
    resolv_content.push_str("options ndots:0\n");

    let resolv_path = etc_dir.join("resolv.conf");
    fs::write(&resolv_path, resolv_content).map_err(|e| {
        AlphenError::Runtime(format!(
            "Failed to write container resolv.conf at {}: {e}",
            resolv_path.display()
        ))
    })?;

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_write_resolv_conf_overrides() {
        let temp_dir = std::env::temp_dir().join(format!(
            "alphen_test_dns_{}",
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::create_dir_all(&temp_dir).unwrap();

        let overrides = vec!["1.1.1.1".to_string(), "9.9.9.9".to_string()];
        write_resolv_conf(&temp_dir, &overrides).unwrap();

        let resolv = temp_dir.join("etc").join("resolv.conf");
        assert!(resolv.exists());
        let content = fs::read_to_string(resolv).unwrap();
        assert!(content.contains("nameserver 1.1.1.1"));
        assert!(content.contains("nameserver 9.9.9.9"));

        let _ = fs::remove_dir_all(&temp_dir);
    }
}
